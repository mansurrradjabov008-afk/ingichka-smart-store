"""
services/handoff_service.py
TASK 5: Human handoff. Strictly follows RULES.md.

1. Handoff triggers:
   - Customer asks for a human (uz/ru/en)
   - Anger or complaint words
   - Grounding validator failed twice
   - 2 consecutive "I don't know" answers
2. On trigger:
   - Reply to customer: "Operatorga ulayman, tez orada javob beradi"
   - Send ADMIN_CHAT_ID: customer name/username, chat_id, 5-line chat summary
     (generated by LLM from real chat), reason for handoff.
3. While in handoff mode:
   - Bot stays silent to the customer.
   - Admin's reply to the forwarded message is delivered to the customer.
4. Admin command /bot_on <chat_id> returns the chat to the bot.
   - Auto-return after 6 hours of admin silence with a polite message.
5. Do not trigger handoff for normal questions.
"""

